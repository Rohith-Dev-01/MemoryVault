-- ============================================================================
-- MEMORY VAULT – DIGITAL LEGACY MANAGEMENT SYSTEM
-- Complete Supabase / PostgreSQL Schema & Seed Data
-- Run this entire script directly inside the Supabase SQL Editor.
-- ============================================================================

-- Enable pgcrypto so we can generate genuine bcrypt ($2a$10$) hashes
-- compatible with PHP 8's password_verify() natively inside PostgreSQL.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Drop existing tables in reverse dependency order for clean re-runs
DROP TABLE IF EXISTS admin_action_logs CASCADE;
DROP TABLE IF EXISTS notification_logs CASCADE;
DROP TABLE IF EXISTS legacy_requests CASCADE;
DROP TABLE IF EXISTS legacy_plans CASCADE;
DROP TABLE IF EXISTS memories CASCADE;
DROP TABLE IF EXISTS final_wishes CASCADE;
DROP TABLE IF EXISTS trusted_contacts CASCADE;
DROP TABLE IF EXISTS digital_assets CASCADE;
DROP TABLE IF EXISTS admin_users CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ============================================================================
-- 1. USERS TABLE
-- ============================================================================
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_handle VARCHAR(60) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    last_check_in TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    escalation_stage INTEGER NOT NULL DEFAULT 0 CHECK (escalation_stage BETWEEN 0 AND 4),
    inactivity_cycle_id VARCHAR(64) NOT NULL DEFAULT 'cycle_initial',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_email ON users (LOWER(email));
CREATE INDEX idx_users_handle ON users (LOWER(user_handle));
CREATE INDEX idx_users_last_check_in ON users (last_check_in);

-- ============================================================================
-- 2. ADMIN USERS TABLE
-- ============================================================================
CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(40) NOT NULL DEFAULT 'reviewer',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_admin_users_email ON admin_users (LOWER(email));

-- ============================================================================
-- 3. DIGITAL ASSETS TABLE
-- SECURITY: Third-party account passwords are NEVER collected or stored.
-- ============================================================================
CREATE TABLE digital_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset_name VARCHAR(140) NOT NULL,
    platform VARCHAR(100) NOT NULL,
    category VARCHAR(80) NOT NULL,
    account_identifier VARCHAR(180) NOT NULL,
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_digital_assets_user_id ON digital_assets (user_id);

-- ============================================================================
-- 4. TRUSTED CONTACTS TABLE
-- SECURITY: Accepting an invitation does NOT grant automatic access to vault data.
-- ============================================================================
CREATE TABLE trusted_contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    phone VARCHAR(40) DEFAULT '',
    relationship VARCHAR(80) NOT NULL,
    invitation_token VARCHAR(80) NOT NULL UNIQUE,
    invitation_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (invitation_status IN ('pending', 'accepted', 'declined')),
    responded_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, email)
);

CREATE INDEX idx_trusted_contacts_user_id ON trusted_contacts (user_id);
CREATE INDEX idx_trusted_contacts_email ON trusted_contacts (LOWER(email));
CREATE INDEX idx_trusted_contacts_token ON trusted_contacts (invitation_token);

-- ============================================================================
-- 5. FINAL WISHES TABLE
-- ============================================================================
CREATE TABLE final_wishes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset_id BIGINT NOT NULL UNIQUE REFERENCES digital_assets(id) ON DELETE CASCADE,
    assigned_contact_id BIGINT NULL REFERENCES trusted_contacts(id) ON DELETE SET NULL,
    action_type VARCHAR(60) NOT NULL CHECK (
        action_type IN (
            'preserve_account',
            'preserve_memories',
            'share_information',
            'request_memorialization',
            'request_deletion'
        )
    ),
    custom_instructions TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_final_wishes_user_id ON final_wishes (user_id);
CREATE INDEX idx_final_wishes_asset_id ON final_wishes (asset_id);
CREATE INDEX idx_final_wishes_contact_id ON final_wishes (assigned_contact_id);

-- ============================================================================
-- 6. MEMORIES & FAREWELL LETTERS TABLE
-- ============================================================================
CREATE TABLE memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    trusted_contact_id BIGINT NULL REFERENCES trusted_contacts(id) ON DELETE SET NULL,
    custom_recipient VARCHAR(140) DEFAULT '',
    title VARCHAR(180) NOT NULL,
    message_body TEXT NOT NULL,
    release_condition VARCHAR(120) NOT NULL DEFAULT 'Upon verified admin approval',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_memories_user_id ON memories (user_id);
CREATE INDEX idx_memories_contact_id ON memories (trusted_contact_id);

-- ============================================================================
-- 7. LEGACY PLANS TABLE
-- ============================================================================
CREATE TABLE legacy_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    first_reminder_days INTEGER NOT NULL DEFAULT 30,
    second_reminder_days INTEGER NOT NULL DEFAULT 35,
    final_reminder_days INTEGER NOT NULL DEFAULT 40,
    trusted_alert_days INTEGER NOT NULL DEFAULT 45,
    general_guidance TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_legacy_plans_user_id ON legacy_plans (user_id);

-- ============================================================================
-- 8. LEGACY ACCESS REQUESTS TABLE
-- IMPORTANT: Inactivity is NOT proof of death. Explicit Admin approval required.
-- ============================================================================
CREATE TABLE legacy_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_code VARCHAR(32) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    trusted_contact_id BIGINT NOT NULL REFERENCES trusted_contacts(id) ON DELETE CASCADE,
    requester_email VARCHAR(180) NOT NULL,
    reason VARCHAR(200) NOT NULL,
    verification_note TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    admin_remarks TEXT DEFAULT '',
    reviewed_by BIGINT NULL REFERENCES admin_users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_legacy_requests_user_id ON legacy_requests (user_id);
CREATE INDEX idx_legacy_requests_status ON legacy_requests (status);
CREATE INDEX idx_legacy_requests_requester_email ON legacy_requests (LOWER(requester_email));

-- ============================================================================
-- 9. NOTIFICATION LOGS TABLE
-- Stores email dispatch records & fallback logs for reliable demo verification.
-- ============================================================================
CREATE TABLE notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_email VARCHAR(180) NOT NULL,
    recipient_role VARCHAR(40) NOT NULL DEFAULT 'user',
    notification_type VARCHAR(60) NOT NULL,
    cycle_id VARCHAR(64) DEFAULT '',
    subject VARCHAR(220) NOT NULL,
    body TEXT NOT NULL,
    delivery_status VARCHAR(30) NOT NULL DEFAULT 'logged',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_notification_logs_user_id ON notification_logs (user_id);
CREATE INDEX idx_notification_logs_dedup ON notification_logs (user_id, cycle_id, notification_type, recipient_email);

-- ============================================================================
-- 10. ADMIN ACTION LOGS TABLE (Audit Trail)
-- ============================================================================
CREATE TABLE admin_action_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
    legacy_request_id BIGINT NULL REFERENCES legacy_requests(id) ON DELETE SET NULL,
    action VARCHAR(60) NOT NULL,
    remarks TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_admin_action_logs_admin_id ON admin_action_logs (admin_id);
CREATE INDEX idx_admin_action_logs_request_id ON admin_action_logs (legacy_request_id);

